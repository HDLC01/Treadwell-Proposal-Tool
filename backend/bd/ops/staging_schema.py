"""Write the BD part of backend/staging/schema_pg.sql from backend/bd/migrations/ (#805).

    python -m bd.ops.staging_schema            # (from backend/) rewrite the part in place
    python -m bd.ops.staging_schema --check    # exit 1 when the committed part is stale

WHY A GENERATED PART. The staging deploy only feeds backend/staging/schema_pg.sql to Postgres,
through a root-owned copy of the deploy program on the server, so BD's schema reaches staging with
no server change only by being in that file. The numbered files stay the one source: this script
copies them in, and tests/test_bd_staging_schema.py fails when the part and the files differ.

What the part does, on every staging deploy (and on a fresh staging database at first start):
  1. makes the bd_app login with a STAGING-ONLY password, when it is missing
  2. takes the runner's advisory lock (bd/migrate.py LOCK_KEY), so a hand run and a deploy take turns
  3. creates schema bd and its ledger, bd.schema_migrations, when missing (the runner's bootstrap)
  4. applies each numbered file ONLY IF the ledger lacks it, with its ledger row and grants.sql, in
     one transaction (psql commits each statement on its own, so a deploy that stops part way never
     leaves a committed file without the privilege model)
  5. re-applies grants.sql once more, so a deploy with nothing pending still repairs privileges
  6. releases the lock
The part goes at the END of the file, after the tool's own tables and roles. It is written with the
file's own line endings and leaves everything outside its two marker lines as it was.
"""
from __future__ import annotations

import argparse
import pathlib
import sys

from .. import migrate

BACKEND = pathlib.Path(__file__).resolve().parents[2]
STAGING_SCHEMA = BACKEND / "staging" / "schema_pg.sql"

BEGIN_MARK = "-- >>> BD CRM: schema bd. GENERATED by backend/bd/ops/staging_schema.py; do not edit by hand. >>>"
END_MARK = "-- <<< BD CRM: end of the generated part <<<"

# STAGING-ONLY. Used by the staging database and nowhere else, never reused: prod's bd_app is made
# by hand on Hanz's go and its password lives only in the prod env file. It guards a database on
# the staging Docker network with no published port, like the PostgREST login above it in the file.
STAGING_ONLY_BD_APP_PASSWORD = "staging_only_bd_app_pw"

BD_APP_ROLE_SQL = (
    "do $bd_role$\n"
    "begin\n"
    "  if not exists (select 1 from pg_catalog.pg_roles where rolname = 'bd_app') then\n"
    "    begin\n"
    "      create role bd_app login password '%s';\n"
    "      -- Set with the role, so no later run ever has to write this cluster-wide setting.\n"
    "      alter role bd_app set search_path = bd, pg_catalog;\n"
    "    exception when duplicate_object or unique_violation then\n"
    "      null;  -- made a moment ago by another session\n"
    "    end;\n"
    "  end if;\n"
    "end\n"
    "$bd_role$;\n" % STAGING_ONLY_BD_APP_PASSWORD
)

_DO_TAG = "$bd_migration$"
_SQL_TAG = "$bd_sql$"


def _header() -> str:
    return (
        "-- The BD CRM's private schema (#802, #805), made from backend/bd/migrations/:\n"
        "-- tests/test_bd_staging_schema.py fails when this part and those files differ. Regenerate it\n"
        "-- from backend/ with `python -m bd.ops.staging_schema` after changing a migration or grants.sql.\n"
        "-- On every deploy: bd_app is made if missing; under the runner's advisory lock, schema bd and\n"
        "-- its ledger are made if missing, each numbered file is applied ONLY IF the ledger lacks it\n"
        "-- (with its ledger row and grants.sql, in one transaction), and grants.sql is re-applied.\n"
        "-- Prod never reads this file: there the runner (python -m bd.migrate) is run by hand on\n"
        "-- Hanz's go.\n"
        "-- Schema bd is not in PostgREST's schemas, and service_role has no rights in it.\n"
    )


def _quoted(name: str, text: str) -> str:
    """`text` as a dollar-quoted literal for EXECUTE, ending in a newline."""
    for tag in (_DO_TAG, _SQL_TAG):
        if tag in text:
            raise SystemExit("%s contains %s, which the staging part uses as its quote" % (name, tag))
    return "%s\n%s%s" % (_SQL_TAG, text if text.endswith("\n") else text + "\n", _SQL_TAG)


def migration_block(path: pathlib.Path) -> str:
    """One numbered file as ONE statement: applied only if the ledger lacks it, then its ledger row
    and grants.sql, all in the do block's one transaction (as the runner applies a file), so psql
    never commits a file without the privilege model."""
    return (
        "-- %(name)s\n"
        "do %(do)s\n"
        "begin\n"
        "  if not exists (select 1 from bd.schema_migrations where name = '%(name)s') then\n"
        "    execute %(body)s;\n"
        "    insert into bd.schema_migrations (name) values ('%(name)s');\n"
        "    execute %(grants)s;\n"
        "  end if;\n"
        "end\n"
        "%(do)s;\n" % {"name": path.name, "do": _DO_TAG,
                        "body": _quoted(path.name, migrate.read_sql(path)),
                        "grants": _quoted(migrate.GRANTS_FILE.name, migrate.grants_sql())}
    )


def render_section() -> str:
    """The whole BD part, marker lines included, with LF line endings."""
    parts = [
        BEGIN_MARK + "\n",
        _header(),
        "\n-- bd_app, the BD CRM's own login. Its password here is STAGING-ONLY: never reused anywhere\n"
        "-- else (prod's bd_app is made by hand and its password lives only in the prod env file).\n",
        BD_APP_ROLE_SQL,
        "\n-- The runner's lock (backend/bd/migrate.py LOCK_KEY), held to the end of this part.\n",
        "do $bd_lock$ begin perform pg_advisory_lock(%d); end $bd_lock$;\n" % migrate.LOCK_KEY,
        migrate.BOOTSTRAP_SQL,
    ]
    for path in migrate.migration_files():
        parts.append("\n" + migration_block(path))
    grants = migrate.grants_sql()
    parts += [
        "\n-- grants.sql, re-applied on every deploy\n",
        grants if grants.endswith("\n") else grants + "\n",
        "\ndo $bd_lock$ begin perform pg_advisory_unlock(%d); end $bd_lock$;\n" % migrate.LOCK_KEY,
        END_MARK + "\n",
    ]
    return "".join(parts)


def current_section(text: str):
    """The BD part as it stands in `text` (LF line endings), or None when there is none."""
    text = text.replace("\r\n", "\n")
    start = text.find(BEGIN_MARK)
    if start < 0:
        return None
    end = text.find(END_MARK, start)
    if end < 0:
        return None
    return text[start:end + len(END_MARK)] + "\n"


def splice(text: str, section: str) -> str:
    """`text` with its BD part replaced by `section` (or added at the end), in text's line endings."""
    newline = "\r\n" if "\r\n" in text else "\n"
    lf = text.replace("\r\n", "\n")
    start = lf.find(BEGIN_MARK)
    if start >= 0:
        end = lf.find(END_MARK, start)
        if end < 0:
            raise SystemExit("schema_pg.sql has the BD part's first marker but not its last")
        tail = lf[end + len(END_MARK):]
        tail = tail[1:] if tail.startswith("\n") else tail
        lf = lf[:start] + section + tail
    else:
        lf = lf.rstrip("\n") + "\n\n" + section
    return lf.replace("\n", newline)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m bd.ops.staging_schema", description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="change nothing; exit 1 when the part is stale")
    ap.add_argument("--file", default=str(STAGING_SCHEMA), help="the staging schema file (default: %(default)s)")
    args = ap.parse_args(argv)
    path = pathlib.Path(args.file)
    raw = path.read_bytes().decode("utf-8")
    section = render_section()
    if args.check:
        if current_section(raw) != section:
            print("%s: the BD part is stale; run python -m bd.ops.staging_schema" % path.name, file=sys.stderr)
            return 1
        return 0
    new = splice(raw, section)
    if new != raw:
        path.write_bytes(new.encode("utf-8"))
        print("wrote the BD part of %s" % path.name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
